import { relations, sql } from "drizzle-orm";
import {
  boolean,
  check,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  text,
  timestamp,
  unique,
  uuid,
} from "drizzle-orm/pg-core";

import { user } from "./auth";
import { products } from "./catalog";

// See ORDER_TRANSITIONS in src/lib/checkout-rules.ts for the allowed moves between statuses.
export const orderStatusEnum = pgEnum("order_status", [
  "pending", // stock reserved, waiting for payment
  "processing", // checkout completed with a delayed payment method
  "paid",
  "failed", // delayed payment failed
  "expired", // abandoned: the Checkout Session expired
  "canceled", // the Checkout Session couldn't be created
  "needs_review", // Stripe's amount or currency didn't match the order
]);

export type OrderStatus = (typeof orderStatusEnum.enumValues)[number];

export type ShippingAddress = {
  name: string | null;
  line1: string | null;
  line2: string | null;
  city: string | null;
  state: string | null;
  postalCode: string | null;
  country: string | null;
};

export const orders = pgTable(
  "orders",
  {
    // Generated by the app so one batch can insert the order and its items.
    id: uuid("id").primaryKey(),
    status: orderStatusEnum("status").notNull().default("pending"),
    userId: text("user_id").references(() => user.id, { onDelete: "set null" }),
    email: text("email"),
    currency: text("currency").notNull().default("usd"),
    subtotal: integer("subtotal").notNull(), // minor units (cents)
    total: integer("total").notNull(), // what Stripe must charge
    stripeCheckoutSessionId: text("stripe_checkout_session_id").unique(),
    stripePaymentIntentId: text("stripe_payment_intent_id").unique(),
    shippingAddress: jsonb("shipping_address").$type<ShippingAddress>(),
    // Set when the reserved units go back to stock, so they're returned only once.
    stockReleased: boolean("stock_released").notNull().default(false),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    paidAt: timestamp("paid_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [
    index("orders_status_expires_at_idx").on(table.status, table.expiresAt),
    index("orders_user_id_idx").on(table.userId),
    check("orders_subtotal_nonnegative", sql`${table.subtotal} >= 0`),
    check("orders_total_nonnegative", sql`${table.total} >= 0`),
  ],
);

// Snapshots of what was bought, so later catalog edits don't rewrite past orders.
export const orderItems = pgTable(
  "order_items",
  {
    id: integer("id").primaryKey().generatedAlwaysAsIdentity(),
    orderId: uuid("order_id")
      .notNull()
      .references(() => orders.id, { onDelete: "cascade" }),
    productId: integer("product_id")
      .notNull()
      .references(() => products.id, { onDelete: "restrict" }),
    slug: text("slug").notNull(),
    name: text("name").notNull(),
    unitPrice: integer("unit_price").notNull(), // minor units (cents)
    quantity: integer("quantity").notNull(),
  },
  (table) => [
    unique("order_items_order_product_key").on(table.orderId, table.productId),
    check("order_items_quantity_range", sql`${table.quantity} between 1 and 99`),
    check("order_items_unit_price_nonnegative", sql`${table.unitPrice} >= 0`),
  ],
);

// Every Stripe webhook event received, for deduplication and auditing.
export const stripeEvents = pgTable("stripe_events", {
  id: text("id").primaryKey(), // evt_…
  type: text("type").notNull(),
  receivedAt: timestamp("received_at", { withTimezone: true }).notNull().defaultNow(),
  processedAt: timestamp("processed_at", { withTimezone: true }),
});

export const ordersRelations = relations(orders, ({ many }) => ({
  items: many(orderItems),
}));

export const orderItemsRelations = relations(orderItems, ({ one }) => ({
  order: one(orders, { fields: [orderItems.orderId], references: [orders.id] }),
  product: one(products, { fields: [orderItems.productId], references: [products.id] }),
}));
